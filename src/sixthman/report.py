"""Write headline findings (league-wide bench rankings) to docs/findings.md.

Usage: python -m sixthman.report   (after the pipeline has run)
"""
from __future__ import annotations

import json

import pandas as pd

from . import config
from .metrics import bench_stints, rank_players

OUT = config.ROOT / "docs" / "findings.md"


def _table(df: pd.DataFrame) -> str:
    cols = {"player": "Player", "team": "Team", "stints": "Stints", "minutes": "Min",
            "score": "Score (pts win %/stint)", "raw_wpa": "Raw WPA total", "avg_entry_leverage": "Avg entry LI"}
    d = df[list(cols)].rename(columns=cols).copy()
    d["Score (pts win %/stint)"] = (100 * d["Score (pts win %/stint)"]).map("{:+.2f}".format)
    d["Raw WPA total"] = d["Raw WPA total"].map("{:+.2f}".format)
    d["Min"] = d["Min"].round(0).astype(int)
    d["Avg entry LI"] = d["Avg entry LI"].round(2)
    head = "| " + " | ".join(d.columns) + " |\n|" + "---|" * len(d.columns) + "\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in r) + " |" for r in d.to_numpy())


def main() -> None:
    st = bench_stints(pd.read_parquet(config.APP_DATA))
    rs = st[(st["phase"] == "Regular season") & st["true_reserve"]]
    overall = rank_players(rs, k=20)
    overall = overall[overall["stints"] >= 50].head(15)
    clutch = rank_players(rs[rs["high_leverage"]], k=10)
    clutch = clutch[clutch["stints"] >= 15].head(10)
    tough = rank_players(rs[rs["opp_strength"] == "Stronger"], k=10)
    tough = tough[tough["stints"] >= 25].head(10)

    team = rs.groupby("team").agg(stints=("wpa", "size"), raw=("wpa", "sum"),
                                  oe=("wpa_over_expected", "sum")).sort_values("oe", ascending=False)
    ev = json.loads((config.PROCESSED_DIR / "wp_model_eval.json").read_text())

    md = f"""# Headline findings: 2025-26 bench players

Generated by `python -m sixthman.report` from the 2025-26 play-by-play (regular season incl.
In-Season Tournament; {rs['game_id'].nunique():,} games, {len(rs):,} bench stints by true reserves,
i.e. players who started at most {config.RESERVE_MAX_START_RATE:.0%} of the games they played).
Score = win probability over expected per stint, shrunk (percentage points of win probability).

## Top reserves overall (min. 50 bench stints, k = 20)
{_table(overall)}

## Top reserves in high-leverage moments (entry leverage >= {config.HIGH_LEVERAGE_THRESHOLD}, min. 15 stints, k = 10)
{_table(clutch)}

## Top reserves against the strongest opposing lineups (top tercile, min. 25 stints, k = 10)
{_table(tough)}

## Team bench totals (sum of WPA over expected across all bench stints)
| Team | Bench stints | Raw WPA | WPA over expected |
|---|---|---|---|
""" + "\n".join(f"| {t} | {int(r.stints)} | {r.raw:+.2f} | {r.oe:+.2f} |" for t, r in team.iterrows()) + f"""

## Model checks
- Win-probability model, game-grouped 5-fold CV: Brier {ev['brier']:.4f} vs {ev['brier_baseline']:.4f}
  for a constant baseline; log loss {ev['log_loss']:.3f} vs {ev['log_loss_baseline']:.3f}
  ({ev['n_games']:,} games, {ev['n_events']:,} regulation events).
- Expected-WPA (context) model R^2 = {ev['expected_wpa_model']['r2']:.3f} over
  {ev['expected_wpa_model']['n_stints']:,} stints: single stints are very noisy, which is why
  rankings are shrunk and shown with error bars.
"""
    OUT.write_text(md)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
